const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ts=require('typescript');
const exportsObject={};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/chart-distributions.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports:exportsObject});
const {histogramBins,densityEstimate}=exportsObject;
assert.equal(histogramBins([]).length,0);
assert.equal(histogramBins([0,0,0])[0].count,3);
const bins=histogramBins([0,1,2,3,4,5,6,7,8,NaN]);
assert.equal(bins.reduce((n,b)=>n+b.count,0),9);
assert.equal(bins.at(-1).count,2);
assert.equal(densityEstimate([1,2,3,4]).length,0);
assert.equal(densityEstimate([1,1,1,1,1]).length,0);
const curve=densityEstimate([0,1,2,3,4]);
assert.equal(curve.length,81);
assert.ok(curve.every(p=>Number.isFinite(p.density)&&p.density>=0));
const integral=curve.slice(1).reduce((sum,p,i)=>sum+(p.x-curve[i].x)*(p.density+curve[i].density)/2,0);
assert.ok(integral>.99&&integral<1.01);
console.log('Histogram conservation and density checks passed.');
